#!/usr/bin/env bash
# Run the packaged account key-vault journey (key-vault W4,
# SharedVaultDockerJourneyTest) on one owned API 35+ AVD against an isolated
# Docker agents fixture. The account's vault is built on the host by core's
# KeyVaultStore (scripts/vault-journey-fixture) holding the fixture's key;
# only Google's chooser and the sync API are faked in-process. Collects
# same-run JUnit XML, screenshots and a credential-redacted logcat, then
# checks them with scripts/check-js-account-vault-results.py.
set -euo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
cd "$ROOT_DIR"
ANDROID_SDK="${ANDROID_SDK:-${ANDROID_SDK_ROOT:-${ANDROID_HOME:-/home/alexey/Android/Sdk}}}"
ADB="${ADB:-$ANDROID_SDK/platform-tools/adb}"
PORT=""
CONTAINER=""
SUFFIX="ikv"
RUN_ID="vaultw4-$(date -u '+%Y%m%dT%H%M%S')"
PREPARE_ONLY=0
TEST_ONLY=0
test_class="com.pocketshell.app.smoke.SharedVaultDockerJourneyTest"
# Throwaway journey values; the journey class carries the same passphrase.
VAULT_PASSPHRASE="pocketshell-vault-test-passphrase journey"
SYNC_PASSPHRASE="pocketshell-vault-test-sync journey"
ALIAS="vault-fixture"

usage() {
  cat <<'USAGE'
Usage: scripts/connected-js-account-vault-docker.sh --port PORT --container NAME [options]

  --port PORT          Isolated agents pool port (2243, 2244 or 2245)
  --container NAME     pocketshell-test-agents-PORT
  --suffix TOKEN       Isolate the debug package (default: ikv)
  --run-id ID          Unique artifact ID (generated by default)
  --prepare-only       Build the suffixed app and androidTest APKs only
  --test-only          Run the prepared APKs on one API 35+ emulator

Evidence: android/app/build/outputs/js-account-vault/<run-id>/
USAGE
}

fail() { printf 'FAIL: %s\n' "$1" >&2; exit 1; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --port) [[ $# -ge 2 ]] || fail '--port needs a value'; PORT="$2"; shift 2 ;;
    --container) [[ $# -ge 2 ]] || fail '--container needs a value'; CONTAINER="$2"; shift 2 ;;
    --suffix) [[ $# -ge 2 ]] || fail '--suffix needs a token'; SUFFIX="$2"; shift 2 ;;
    --run-id) [[ $# -ge 2 ]] || fail '--run-id needs a value'; RUN_ID="$2"; shift 2 ;;
    --prepare-only) PREPARE_ONLY=1; shift ;;
    --test-only) TEST_ONLY=1; shift ;;
    --help|-h) usage; exit 0 ;;
    *) fail "unknown argument: $1" ;;
  esac
done

[[ "$SUFFIX" =~ ^[A-Za-z0-9._]+$ ]] || fail "suffix must match [A-Za-z0-9._]+ (got: $SUFFIX)"
[[ "$RUN_ID" =~ ^[A-Za-z0-9][A-Za-z0-9_-]{2,48}$ ]] || fail 'run ID must be 3-49 path-safe characters'
(( PREPARE_ONLY + TEST_ONLY <= 1 )) || fail '--prepare-only and --test-only cannot be combined'
if [[ "$PREPARE_ONLY" != 1 ]]; then
  [[ "$PORT" =~ ^(2243|2244|2245)$ ]] || fail '--port must be an isolated pool port: 2243, 2244, or 2245'
  [[ "$CONTAINER" == "pocketshell-test-agents-$PORT" ]] || fail "--container must be pocketshell-test-agents-$PORT"
fi
[[ -f "$ROOT_DIR/tests/docker/test_key" ]] || fail 'Docker fixture key is missing'
"$ROOT_DIR/scripts/check-js-account-vault-results.py" --self-test

source "$ROOT_DIR/scripts/lib/disk-preflight.sh"
source "$ROOT_DIR/scripts/lib/gradle-output-lock.sh"
source "$ROOT_DIR/scripts/lib/avd-lock.sh"
source "$ROOT_DIR/scripts/lib/android-input-preflight.sh"

pocketshell_disk_preflight "$ROOT_DIR/android" 'connected-js-account-vault-docker.sh' || exit $?
pocketshell_acquire_gradle_output_lock "$ROOT_DIR/android" '' "connected-js-account-vault-docker.sh suffix=$SUFFIX run=$RUN_ID"

if [[ "$TEST_ONLY" != 1 ]]; then
  "$ROOT_DIR/scripts/assemble-debug.sh" --suffix "$SUFFIX"
  "$ROOT_DIR/android/gradlew" -p "$ROOT_DIR/android" :app:assembleDebugAndroidTest \
    "-PpocketshellAppIdSuffix=$SUFFIX" --stacktrace --console=plain
fi
if [[ "$PREPARE_ONLY" == 1 ]]; then
  printf 'PASS: packaged account key-vault journey APKs prepared for suffix %s\n' "$SUFFIX"
  exit 0
fi

docker inspect "$CONTAINER" >/dev/null 2>&1 || fail "Docker fixture container is missing: $CONTAINER"
health="$(docker inspect --format '{{.State.Health.Status}}' "$CONTAINER" 2>/dev/null || true)"
[[ "$health" == healthy ]] || fail "Docker fixture must be healthy; $CONTAINER reports ${health:-no health status}"

if [[ -z "${ANDROID_SERIAL:-}" ]]; then
  mapfile -t online_emulators < <("$ADB" devices | awk '$1 ~ /^emulator-/ && $2 == "device" { print $1 }')
  (( ${#online_emulators[@]} == 1 )) || fail "expected one online emulator or ANDROID_SERIAL; found ${#online_emulators[@]}"
  export ANDROID_SERIAL="${online_emulators[0]}"
fi
[[ "$("$ADB" -s "$ANDROID_SERIAL" get-state 2>/dev/null || true)" == device ]] || fail "selected Android device is not online: $ANDROID_SERIAL"
device_api="$("$ADB" -s "$ANDROID_SERIAL" shell getprop ro.build.version.sdk | tr -d '\r')"
[[ "$device_api" =~ ^[0-9]+$ ]] && (( device_api >= 35 )) || fail "the vault journey requires API 35+; got ${device_api:-unknown}"

export POCKETSHELL_AVD_LOCK_CONTINUOUS=1
export POCKETSHELL_AVD_LOCK_FILE="$(pocketshell_avd_lock_file_for_serial "$ROOT_DIR" "$ANDROID_SERIAL")"
pocketshell_acquire_avd_lock "$ROOT_DIR"
pocketshell_assert_avd_lock_owned "$POCKETSHELL_AVD_LOCK_FILE"

RESULTS_DIR="$ROOT_DIR/android/app/build/outputs/androidTest-results/connected/debug"
ARTIFACTS_DIR="$ROOT_DIR/android/app/build/outputs/js-account-vault/$RUN_ID"
[[ ! -e "$ARTIFACTS_DIR" ]] || fail "refusing to overwrite existing run artifacts: $ARTIFACTS_DIR"
rm -rf -- "$RESULTS_DIR"
mkdir -p "$ARTIFACTS_DIR/instrumentation-results" "$ARTIFACTS_DIR/device-screenshots"
pocketshell_android_apply_lane_settings "$ADB" "$ANDROID_SERIAL" "$ARTIFACTS_DIR/lane-settings.txt" \
  || fail "could not apply the lane input settings on $ANDROID_SERIAL"
pocketshell_run_without_avd_lock_fd "$ADB" -s "$ANDROID_SERIAL" logcat -c >/dev/null 2>&1 || true

# The account the web wrote: a real vault holding the fixture key, bound to
# the fixture host as the emulator reaches it, and the host list.
fixture_local="$ARTIFACTS_DIR/.vault-fixture.json"
node "$ROOT_DIR/scripts/vault-journey-fixture/build.mjs" \
  --key "$ROOT_DIR/tests/docker/test_key" --alias "$ALIAS" --hostname 10.0.2.2 --port "$PORT" --user testuser \
  --passphrase "$VAULT_PASSPHRASE" --sync-passphrase "$SYNC_PASSPHRASE" --gateway-auth host --out "$fixture_local" \
  > "$ARTIFACTS_DIR/vault-fixture-build.txt" 2>&1 || { cat "$ARTIFACTS_DIR/vault-fixture-build.txt" >&2; fail 'vault fixture build failed'; }
python3 - "$fixture_local" > "$ARTIFACTS_DIR/vault-fixture-slots.txt" <<'PY'
import json, sys
fixture = json.load(open(sys.argv[1]))
print("alias=" + fixture["alias"])
print("keyId=" + fixture["keyId"])
for slot, value in sorted(fixture["slots"].items()):
    print(f"slot={slot} version={value['version']} bytes={len(value['data'])}")
PY
DEVICE_FIXTURE="/data/local/tmp/pocketshell-vault-fixture-$RUN_ID.json"
cleanup() {
  "$ADB" -s "$ANDROID_SERIAL" shell rm -f "$DEVICE_FIXTURE" >/dev/null 2>&1 || true
  rm -f -- "$fixture_local"
}
trap cleanup EXIT
"$ADB" -s "$ANDROID_SERIAL" push "$fixture_local" "$DEVICE_FIXTURE" > "$ARTIFACTS_DIR/stage-vault-fixture.txt"

SCREENSHOT_DIR="/sdcard/Pictures/PocketShell/JsVaultJourney/$RUN_ID"
printf 'Running packaged account key-vault journey on %s (API %s), suffix %s, port %s, run %s\n' \
  "$ANDROID_SERIAL" "$device_api" "$SUFFIX" "$PORT" "$RUN_ID"
test_status=0
pocketshell_run_without_avd_lock_fd "$ROOT_DIR/android/gradlew" -p "$ROOT_DIR/android" :app:connectedDebugAndroidTest \
  "-PpocketshellAppIdSuffix=$SUFFIX" \
  "-Pandroid.testInstrumentationRunnerArguments.class=$test_class" \
  "-Pandroid.testInstrumentationRunnerArguments.screenshotRunId=$RUN_ID" \
  "-Pandroid.testInstrumentationRunnerArguments.vaultFixture=$DEVICE_FIXTURE" \
  --stacktrace --console=plain 2>&1 | tee "$ARTIFACTS_DIR/gradle.log" || test_status=${PIPESTATUS[0]}

shopt -s nullglob
junit_files=("$RESULTS_DIR"/TEST-*.xml)
shopt -u nullglob
(( ${#junit_files[@]} > 0 )) && cp -a -- "${junit_files[@]}" "$ARTIFACTS_DIR/instrumentation-results/"
# Credential-bearing lines never reach the artifact (they would also fail the checker).
pocketshell_run_without_avd_lock_fd "$ADB" -s "$ANDROID_SERIAL" logcat -d -v threadtime 2>&1 \
  | python3 -c '
import re, sys
pattern = re.compile(r"PRIVATE KEY-----|pocketshell-vault-test-|\"privateKeyPem\"\s*:|\"passphrase\"\s*:", re.IGNORECASE)
redacted = 0
with open(sys.argv[1], "w", encoding="utf-8") as out:
    for line in sys.stdin:
        if pattern.search(line):
            redacted += 1
            out.write("[REDACTED Android log line containing credential material]\n")
        else:
            out.write(line)
open(sys.argv[2], "w").write(f"sensitive_log_lines_redacted={redacted}\n")
' "$ARTIFACTS_DIR/logcat.txt" "$ARTIFACTS_DIR/logcat-redaction.txt"
while IFS= read -r screenshot; do
  screenshot="${screenshot%$'\r'}"
  [[ "$screenshot" == *.png ]] || continue
  pocketshell_run_without_avd_lock_fd "$ADB" -s "$ANDROID_SERIAL" pull "$SCREENSHOT_DIR/$screenshot" \
    "$ARTIFACTS_DIR/device-screenshots/$screenshot" >/dev/null || fail "could not retrieve packaged screenshot: $screenshot"
done < <(pocketshell_run_without_avd_lock_fd "$ADB" -s "$ANDROID_SERIAL" shell "ls '$SCREENSHOT_DIR' 2>/dev/null" || true)
relative_screenshot_dir="Pictures/PocketShell/JsVaultJourney/$RUN_ID/"
pocketshell_run_without_avd_lock_fd "$ADB" -s "$ANDROID_SERIAL" shell \
  "content delete --uri content://media/external/images/media --where \"relative_path='$relative_screenshot_dir'\"" >/dev/null 2>&1 || true
pocketshell_run_without_avd_lock_fd "$ADB" -s "$ANDROID_SERIAL" shell "rm -rf '$SCREENSHOT_DIR'" >/dev/null 2>&1 || true

(( test_status == 0 )) || fail "connected account key-vault journey failed (exit $test_status); evidence in $ARTIFACTS_DIR"

"$ROOT_DIR/scripts/check-js-account-vault-results.py" \
  --results-dir "$ARTIFACTS_DIR/instrumentation-results" \
  --screenshots-dir "$ARTIFACTS_DIR/device-screenshots" \
  --logcat-redaction "$ARTIFACTS_DIR/logcat-redaction.txt"
printf 'PASS: packaged account key-vault journey completed. Artifacts: %s\n' "$ARTIFACTS_DIR"
